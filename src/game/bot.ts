import type { Client } from "colyseus";
import type { FindTheBotRoom } from "./room.js";

export class BotController {
  private readonly room: FindTheBotRoom;
  private readonly botId: string;

  constructor(room: FindTheBotRoom, botId: string) {
    this.room = room;
    this.botId = botId;
  }

  get id(): string {
    return this.botId;
  }

  tick(deltaMs: number): void {
    const bot = this.room.state.players.get(this.botId);
    if (!bot || bot.eliminated || this.room.state.phase !== "travel") return;

    const direction = Math.random() > 0.5 ? 1 : -1;
    bot.x = Math.max(-20, Math.min(20, bot.x + direction * deltaMs * 0.002));
    bot.z = Math.max(-20, Math.min(20, bot.z + (Math.random() - 0.5) * deltaMs * 0.001));
  }

  vote(targetId: string | null): void {
    this.room.castVote(this.botId, targetId);
  }

  onClientMessage(_client: Client, _message: unknown): void {
    // Bot input is generated by the server, not accepted from clients.
  }
}
